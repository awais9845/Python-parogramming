# 1. Arithmetic Operators

# are used to perform a methematical operation 
# like adding, subtraction, multiplication, division, modoules, power


# for addition +

# used to add two numbers 

num_1 = int(input("Please enter the first num."))
num_2 = int(input("Please enter the second num."))


numbers_Addition = num_1 + num_2 
# here + is arithmetic operator

numbers_Subtraction = num_1 - num_2
# here - is arithmetic operator

numbers_Multiplication = num_1 * num_2
# here * is arithmetic operator

numbers_Division = num_1 / num_2
# here / is arithmetic operator

numbers_modoules = num_1 % num_2
# here % is arithmetic operator

numbers_Power = num_1 ** num_2
# here ** (power) is arithmetic operator



print(f"The addition of the two number is {numbers_Addition}")
print(f"The subtration of the two number is {numbers_Subtraction}")
print(f"The multiplication of the two number is {numbers_Multiplication}")
print(f"The division of the two number is {numbers_Division}")
print(f"The modoules of the two number is {numbers_modoules}")
print(f"The power of the two number is {numbers_Power}")


